#!/usr/bin/env bash
# Re-run every sampling arm at 10-80% under the corrected probability
# normalisation. See generate_modcog_revised8_renorm_suite.py for what and why.
#
# Two sizes in sequence: H = 512 first (3,480 runs, six arms -- the paper's
# core), then H = 1024 (600 runs, snp_rescale only, the size check). H = 512
# goes first so that if the machine is interrupted overnight the part the paper
# depends on is the part that finished.
#
# RESUMABLE. Every config carries `resume: true`, the harness treats a row with
# a non-empty `error` as not completed, and results are written through a
# temporary file and an atomic rename, so a kill mid-write cannot truncate a
# CSV. Re-running this script picks up exactly where it stopped; completed runs
# are skipped, not repeated.
#
# JOBS defaults to 8. This machine has 11 cores and 18 GB, and the per-worker
# footprint is dominated by the S-NP observable matrix (25,000 samples x H
# units): ~100 MB per worker at H = 512, ~200 MB at H = 1024, on top of the
# model and the cached eval batches. 8 leaves headroom on a run measured in
# hours; 12 does not.
#
# Runs under `caffeinate -dimsu` so neither the display sleeping nor the system
# idling can stop it. The whole launcher re-execs itself under caffeinate, so
# the assertion covers every worker, not just the parent.
#
# NOTE -- do not edit this file while it is running; bash reads scripts
# incrementally. Copy it and run the copy instead.
#
# Usage:
#   scripts/run_modcog_revised8_renorm.sh [PYTHON] [JOBS] [THREADS] [SIZES]
#   scripts/run_modcog_revised8_renorm.sh ../.venv/bin/python 8 1 "512 1024"

set -uo pipefail

if [[ "${RENORM_CAFFEINATED:-0}" != "1" ]]; then
  export RENORM_CAFFEINATED=1
  exec caffeinate -dimsu "$0" "$@"
fi

PYTHON="${1:-python3}"
MAX_JOBS="${2:-8}"
THREADS="${3:-1}"
SIZES="${4:-512 1024}"

TASKS=(ctxdlydm2intseq ctxdlydm1intseq dlydm1intseq dlydm2intseq
       multidlydmintseq dm1seqr dm2seql dmsintseq)
SPARSITIES=(p10 p20 p30 p40 p50 p60 p70 p80)

export OMP_NUM_THREADS="${THREADS}" MKL_NUM_THREADS="${THREADS}"
export OPENBLAS_NUM_THREADS="${THREADS}" VECLIB_MAXIMUM_THREADS="${THREADS}"
export NUMEXPR_NUM_THREADS="${THREADS}" TORCH_NUM_THREADS="${THREADS}"
export PYTORCH_ENABLE_MPS_FALLBACK=1

overall=0
started_all=$(date +%s)

for HIDDEN in ${SIZES}; do
  STEM="task_preservation_tanh_h${HIDDEN}_modcog_revised8_12k_seqbest_renorm_p10_80"
  CONFIG_DIR="configs/${STEM}"
  LOG_DIR="results/${STEM}/logs"
  mkdir -p "${LOG_DIR}"
  # Clear stale logs so a later grep cannot count a previous attempt's failures
  # as current ones. That cost real diagnostic time once.
  rm -f "${LOG_DIR}"/*.log

  echo "=============================================================="
  echo "H = ${HIDDEN}: generating configs (checkpoint presence enforced)"
  echo "=============================================================="
  "${PYTHON}" scripts/generate_modcog_revised8_renorm_suite.py --hidden-size "${HIDDEN}" || exit 1

  UNITS=()
  for t in "${TASKS[@]}"; do for p in "${SPARSITIES[@]}"; do UNITS+=("${t}_${p}"); done; done

  echo
  echo "H = ${HIDDEN}: ${#UNITS[@]} units, up to ${MAX_JOBS} workers x ${THREADS} threads"
  echo "  started $(date '+%Y-%m-%d %H:%M:%S')"
  started=$(date +%s)

  declare -a PIDS=() PIDUNIT=()
  for unit in "${UNITS[@]}"; do
    while (( $(jobs -rp | wc -l) >= MAX_JOBS )); do sleep 10; done
    cfg="${CONFIG_DIR}/${STEM}_${unit}.json"
    log="${LOG_DIR}/${unit}.log"
    "${PYTHON}" -u -m pruning_benchmark --mode suite --config "${cfg}" > "${log}" 2>&1 &
    PIDS+=("$!"); PIDUNIT+=("${unit}")
  done

  failed=0
  for i in "${!PIDS[@]}"; do
    if ! wait "${PIDS[$i]}"; then
      echo "  FAILED ${PIDUNIT[$i]} -- see ${LOG_DIR}/${PIDUNIT[$i]}.log" >&2
      failed=$((failed + 1)); overall=1
    fi
  done
  unset PIDS PIDUNIT

  elapsed=$(( $(date +%s) - started ))
  rows=$(cat "results/${STEM}"/*.csv 2>/dev/null | grep -cv '^run_id' || echo 0)
  echo
  echo "H = ${HIDDEN}: finished in $((elapsed / 3600))h $(((elapsed % 3600) / 60))m"
  echo "  units failed: ${failed} of ${#UNITS[@]}"
  echo "  rows now in results/${STEM}: ${rows}"
done

total=$(( $(date +%s) - started_all ))
echo
echo "=============================================================="
echo "all sizes done in $((total / 3600))h $(((total % 3600) / 60))m"
if (( overall == 0 )); then
  echo "no unit failed. Regenerate the statistics next:"
  echo "  .venv/bin/python analysis/paper_statistics/run_paper_stats.py"
  echo "  .venv/bin/python analysis/paper_statistics/key_comparisons.py"
else
  echo "one or more units failed; re-run this script to resume" >&2
fi
exit "${overall}"
